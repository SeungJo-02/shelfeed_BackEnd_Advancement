// 일정 비율로 cache-buster 변형을 섞어 실서비스에 가까운 캐시 미스 유도
// - 80%: 고정 키워드 (Zipf 분포 흉내 — 상위 20개에 가중치)
// - 20%: 랜덤 변형 (`keyword + 숫자`) → 항상 캐시 미스
export function pickQuery() {
  const r = Math.random();
  if (r < 0.2) {
    const base = KEYWORDS[Math.floor(Math.random() * KEYWORDS.length)];
    return `${base}${Math.floor(Math.random() * 10000)}`;
  }
  if (r < 0.6) {
    return KEYWORDS[Math.floor(Math.random() * 20)];
  }
  return KEYWORDS[Math.floor(Math.random() * KEYWORDS.length)];
}
